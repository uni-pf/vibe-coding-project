/**
 * 相机路线 —— 滚轮驱动的固定路线（新增）
 *
 * 两个关键点数组，**一一对应、长度必须相同**：
 *   camera  相机「站在哪」—— 滚轮推进时相机沿这条线走
 *   look    相机「看向哪」—— 同一时刻视线落在这条线的对应点上
 *
 * 为什么用两条线而不是一条：
 *   只给一条相机路径的话，视线方向只能靠代码去猜「现在该看哪件物件」，
 *   路线一改就得跟着重算，转弯也会很生硬。拆成两条线之后，
 *   转向本身也变成了数据 —— 想让相机在行程后半段看向右边，挪 look 的点就行。
 *
 * look 后三个点就是三件物件的坐标本身（台灯那点把 y 抬到了灯罩高度），
 * 所以相机停在第 i 个机位时，第 i 件物件正好落在画面中心。
 *
 * ⚠️ 两条线必须用同一种参数化取点（代码里用 getPoint，等参数）。
 *    曾经用过 getPointAt（等弧长）—— 两条曲线弧长不等，同一个进度在两条线上对不上号，
 *    实测相机走到 90% 路程时视线已滑到约 97%，物件被甩到画面边上。
 *    改成 getPoint 后，第 i 个相机关键点严格对应第 i 个视线关键点。
 *
 * routeRange 怎么定（4 个控制点 → 等参数下三个机位的进度）：
 *   第 i 个关键点在 4 点曲线上的进度 = i / 3
 *   → 台灯机位 ≈ 0.33、笔记本机位 ≈ 0.67、唱片机位 = 1.00
 *   各物件的 routeRange 就围着这三个数留余量。
 *
 * ⚠️ 改了这里的点数或位置，routeRange 必须跟着重算，否则会出现
 *    「相机还没走到，物件就已经能点」或者「走到了却点不了」。
 */
